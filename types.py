# 10         -> int (tam ədəd)
# 10.0       -> float (kəsr ədəd)
# "10"       -> str (mətn)
# True       -> bool (məntiqi tip)
# "True"     -> str (dırnaq daxilində olduğu üçün mətn)
# 3 + 2.0    -> float (nəticə 5.0 olur, yəni kəsr)
# "3" + "2"  -> str (iki mətn birləşir, nəticə "32" olur)
# 10 / 2     -> float (bölmə əməliyyatı həmişə float qaytarır, nəticə 5.0)

# Tiplərin type() funksiyası ilə yoxlanılması
print(type(10))
print(type(10.0))
print(type("10"))
print(type(True))
print(type("True"))
print(type(3 + 2.0))
print(type("3" + "2"))
print(type(10 / 2))

